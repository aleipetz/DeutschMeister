#!/usr/bin/env python3
"""Builds the app from Content/data + App/* sources.

Two outputs:
  1. App/data.js        — generated (gitignored), lets App/index.html be opened
                           directly during development and always reflect the
                           latest content without a full dist build.
  2. dist/german-vocab.html — the single self-contained file the user actually
                           opens; inlines styles.css/engine.js/speech.js/app.js
                           and the data.js content directly into index.html.

Usage:
    python3 Tools/build.py

Run Tools/validate_content.py first — this script does not re-validate.
"""
import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "Content" / "data"
APP_DIR = ROOT / "Prototype" / "App"
DIST_DIR = ROOT / "Prototype" / "dist"
CEFR_LEVELS = ["A1", "A2", "B1", "B2", "C1", "C2"]


def load_entries():
    entries = []
    for level in CEFR_LEVELS:
        level_dir = DATA_DIR / level.lower()
        if not level_dir.exists():
            continue
        for json_file in sorted(level_dir.glob("*.json")):
            data = json.loads(json_file.read_text())
            entries.extend(data.get("entries", []))
    return entries


def load_themes():
    themes_file = DATA_DIR / "_shared" / "themes.json"
    if not themes_file.exists():
        return []
    return json.loads(themes_file.read_text()).get("themes", [])


def build_verb_families(entries):
    by_base = defaultdict(list)
    for e in entries:
        verb = e.get("verb")
        if verb and verb.get("base_verb"):
            by_base[verb["base_verb"]].append({
                "id": e["id"],
                "lemma_de": e["lemma_de"],
                "particle": verb.get("particle"),
                "particle_meaning_hint": verb.get("particle_meaning_hint"),
            })
    families = [
        {"base_verb": base, "members": sorted(members, key=lambda m: m["id"])}
        for base, members in sorted(by_base.items())
    ]
    return {"schemaVersion": 1, "families": families}


def generate_data_js(entries, themes, families):
    return (
        "// GENERATED by Tools/build.py — do not hand-edit. Re-run the build to refresh.\n"
        f"const VOCAB_ENTRIES = {json.dumps(entries, ensure_ascii=False)};\n"
        f"const THEMES = {json.dumps(themes, ensure_ascii=False)};\n"
        f"const VERB_FAMILIES = {json.dumps(families, ensure_ascii=False)};\n"
    )


def inline_between(html, start_marker, end_marker, replacement):
    start_idx = html.index(start_marker)
    end_idx = html.index(end_marker) + len(end_marker)
    return html[:start_idx] + replacement + html[end_idx:]


def build_dist_html(data_js):
    template = (APP_DIR / "index.html").read_text()
    css = (APP_DIR / "styles.css").read_text()
    engine_js = (APP_DIR / "engine.js").read_text()
    speech_js = (APP_DIR / "speech.js").read_text()
    quiz_js = (APP_DIR / "quiz.js").read_text()
    app_js = (APP_DIR / "app.js").read_text()

    html = inline_between(
        template,
        "<!--BUILD:STYLE_START-->", "<!--BUILD:STYLE_END-->",
        "<!--BUILD:STYLE_START-->\n<style>\n" + css + "\n</style>\n<!--BUILD:STYLE_END-->",
    )
    combined_js = "\n".join([data_js, engine_js, speech_js, quiz_js, app_js])
    html = inline_between(
        html,
        "<!--BUILD:SCRIPT_START-->", "<!--BUILD:SCRIPT_END-->",
        "<!--BUILD:SCRIPT_START-->\n<script>\n" + combined_js + "\n</script>\n<!--BUILD:SCRIPT_END-->",
    )
    return html


def main():
    entries = load_entries()
    themes = load_themes()
    families = build_verb_families(entries)

    data_js = generate_data_js(entries, themes, families)
    (APP_DIR / "data.js").write_text(data_js)
    print(f"Wrote {APP_DIR / 'data.js'} ({len(entries)} entries, {len(themes)} themes)")

    DIST_DIR.mkdir(parents=True, exist_ok=True)
    dist_html = build_dist_html(data_js)
    dist_path = DIST_DIR / "german-vocab.html"
    dist_path.write_text(dist_html)
    size_kb = dist_path.stat().st_size / 1024
    print(f"Wrote {dist_path} ({size_kb:.0f} KB)")
    print(f"\nOpen it directly: open '{dist_path}'" if sys.platform == "darwin" else f"\nOpen {dist_path} in your browser.")


if __name__ == "__main__":
    main()
