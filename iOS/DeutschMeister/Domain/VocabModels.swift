import Foundation

enum CEFRLevel: String, CaseIterable, Codable, Comparable, Hashable, Sendable {
    case a1 = "A1", a2 = "A2", b1 = "B1", b2 = "B2", c1 = "C1", c2 = "C2"

    static func < (lhs: CEFRLevel, rhs: CEFRLevel) -> Bool {
        allCases.firstIndex(of: lhs)! < allCases.firstIndex(of: rhs)!
    }
}

enum PartOfSpeech: String, CaseIterable, Codable, Hashable, Sendable {
    case noun
    case adjective
    case verb
    case phrasalVerb = "phrasal_verb"
    case compositeVerb = "composite_verb"
    case other

    var label: String {
        switch self {
        case .noun: "Noun"
        case .adjective: "Adjective"
        case .verb: "Verb"
        case .phrasalVerb: "Phrasal Verb"
        case .compositeVerb: "Composite Verb"
        case .other: "Word"
        }
    }

    var isSeparableFamily: Bool { self == .phrasalVerb || self == .compositeVerb }
}

enum Gender: String, CaseIterable, Codable, Hashable, Sendable {
    case der, die, das
}

struct NounInfo: Codable, Hashable, Sendable {
    var gender: Gender
    var pluralDE: String?

    enum CodingKeys: String, CodingKey {
        case gender
        case pluralDE = "plural_de"
    }
}

struct VerbInfo: Codable, Hashable, Sendable {
    var separable: Bool
    var irregular: Bool
    var present3sg: String
    var perfekt: String
    var praeteritum3sg: String?
    var baseVerb: String?
    var particle: String?
    var particleMeaningHint: String?

    enum CodingKeys: String, CodingKey {
        case separable, irregular, perfekt, particle
        case present3sg = "present_3sg"
        case praeteritum3sg = "praeteritum_3sg"
        case baseVerb = "base_verb"
        case particleMeaningHint = "particle_meaning_hint"
    }
}

struct AdjectiveInfo: Codable, Hashable, Sendable {
    var comparativeIrregular: String?
    var superlativeIrregular: String?

    enum CodingKeys: String, CodingKey {
        case comparativeIrregular = "comparative_irregular"
        case superlativeIrregular = "superlative_irregular"
    }
}

/// One vocabulary entry. Mirrors `Content/schema/SCHEMA.md`.
struct VocabEntry: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var cefr: CEFRLevel
    var pos: PartOfSpeech
    var lemmaDE: String
    var translationsEN: [String]
    var exampleDE: String
    var exampleEN: String
    var clozeWord: String
    var themes: [String]
    /// 1 = essential/common, 5 = rare. Drives ordering and XP.
    var priority: Int
    var notes: String?
    var noun: NounInfo?
    var verb: VerbInfo?
    var adjective: AdjectiveInfo?

    enum CodingKeys: String, CodingKey {
        case id, cefr, pos, priority, notes, noun, verb, adjective, themes
        case lemmaDE = "lemma_de"
        case translationsEN = "translations_en"
        case exampleDE = "example_de"
        case exampleEN = "example_en"
        case clozeWord = "cloze_word"
    }

    var primaryTranslation: String { translationsEN.first ?? "" }
}

struct Theme: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var labelEN: String
    var icon: String

    enum CodingKeys: String, CodingKey {
        case id, icon
        case labelEN = "label_en"
    }

    static let general = Theme(id: "general", labelEN: "General", icon: "📘")
}

/// Contents of `vocab-bundle.json` (generated by `Tools/build_bundle.py`).
struct VocabBundle: Codable, Sendable {
    var schemaVersion: Int
    var themes: [Theme]
    var entries: [VocabEntry]
}

struct VerbFamily: Identifiable, Hashable, Sendable {
    struct Member: Hashable, Sendable {
        var id: String
        var lemmaDE: String
        var particle: String?
        var particleMeaningHint: String?
    }

    var baseVerbID: String
    var members: [Member]
    var id: String { baseVerbID }
}
